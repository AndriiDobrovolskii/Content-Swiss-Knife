/**
 * protected-name-precedence.spec.ts — US-7.1 T8 (FR-2, FR-6, FR-7, NFR-1).
 *
 * `PRODUCT_NAME_LOCALIZATION` is "THE single copy" of the rule that translates the generic descriptive
 * category and puts it first. It is interpolated into MASTER_SYSTEM_PROMPT (and through it into the
 * Optimizer's master block) and six times into Task C. T8 adds ONE leading, product-independent
 * precedence clause to it: when the request carries a `[PROTECTED PRODUCT NAME]` block, every token
 * is kept in order, untranslated and verbatim once, overriding the descriptor-translation and
 * category-first rules below and any inline instruction elsewhere; only number/unit locale formatting
 * is allowed. Generic-name text is unchanged.
 *
 * The marker literal is the SAME one protected-name-block.spec.ts asserts for the dynamic block, so the
 * static clause and the per-product block cannot drift apart (a mismatch would make the clause refer to
 * a block the model never sees).
 *
 * Product-independent by design (plan D5): the clause lives in cached text, so it may not mention any
 * product. The one-time cache re-warm after this text changes is accepted by the plan.
 *
 * Existing pins this change must not break (checked at TEST_WRITING, all green today):
 *  - master-system-prompt.spec.ts:132 anchors on the [HEADING FORM — applies to every block header,
 *    not on the constant, so it is unaffected;
 *  - the full-description goldens move once and are regenerated by so-builder (see the golden spec).
 */
import { describe, it, expect } from 'vitest';
import { PRODUCT_NAME_LOCALIZATION } from './constants';
import { MASTER_SYSTEM_PROMPT } from './master-system-prompt';
import { buildOptimizerPrompt } from '../prompts/optimizer';
import { buildPromptC } from '../prompts/task-c';

const MARKER = '[PROTECTED PRODUCT NAME]';
const collapse = (s: string) => s.replace(/\s+/g, ' ');

describe('PRODUCT_NAME_LOCALIZATION — the leading protected-name precedence clause (T8, FR-2)', () => {
  const at = PRODUCT_NAME_LOCALIZATION.indexOf(MARKER);
  const clause = collapse(PRODUCT_NAME_LOCALIZATION.slice(Math.max(0, at - 200), at + 1400));

  it('names the [PROTECTED PRODUCT NAME] block it defers to', () => {
    expect(at).toBeGreaterThanOrEqual(0);
  });

  it('comes FIRST: before the three-part split and the category-first word-order rule it overrides', () => {
    expect(at).toBeGreaterThanOrEqual(0);   // not vacuous: an absent marker (-1) must not satisfy the ordering
    expect(at).toBeLessThan(PRODUCT_NAME_LOCALIZATION.indexOf('Split the Product Name into three parts'));
    expect(at).toBeLessThan(PRODUCT_NAME_LOCALIZATION.indexOf('WORD ORDER:'));
  });

  it('keeps every token, in order, untranslated, verbatim and rendered once', () => {
    expect(clause).toMatch(/every token/i);
    expect(clause).toMatch(/in (the )?(typed |same |original )?order|order/i);
    expect(clause).toMatch(/untranslated|never translat|not translat|do not translat/i);
    expect(clause).toMatch(/verbatim/i);
    expect(clause).toMatch(/\bonce\b/i);
  });

  it('says it overrides the descriptor-translation and category-first rules, and any inline instruction', () => {
    expect(clause).toMatch(/overrid|takes precedence|supersed|wins over/i);
    expect(clause).toMatch(/descriptor|translat/i);
    expect(clause).toMatch(/category-first/i);
    expect(clause).toMatch(/inline|elsewhere/i);
  });

  it('permits only locale formatting of numbers and units inside the name', () => {
    expect(clause).toMatch(/number/i);
    expect(clause).toMatch(/unit/i);
    expect(clause).toMatch(/only/i);
  });

  it('is product-independent: no product or brand from the fixtures appears in the cached text', () => {
    expect(PRODUCT_NAME_LOCALIZATION).not.toContain('Form Studio');
    expect(PRODUCT_NAME_LOCALIZATION).not.toContain('Resin Tank');
  });

  it('generic-name behaviour text is unchanged (regression guard, passes today)', () => {
    const flat = collapse(PRODUCT_NAME_LOCALIZATION);
    expect(flat).toContain('GENERIC DESCRIPTIVE CATEGORY');
    expect(flat).toContain('TRANSLATE it into the target language');
    expect(flat).toContain('category-first → [Translated descriptive]');
    expect(flat).toContain('English (en-GB / en-ES / en-US): brand-first');
  });
});

describe('the clause reaches every prompt that interpolates the constant (FR-2, FR-6, FR-7)', () => {
  it('MASTER_SYSTEM_PROMPT carries it (Generator / UA Description / Slugs-adjacent master)', () => {
    expect(MASTER_SYSTEM_PROMPT).toContain(MARKER);
  });

  it('the Optimizer\'s cached master block carries it (the Optimizer does not import the constant itself)', () => {
    const payload = buildOptimizerPrompt('<p>x</p>', 'Formlabs Form Studio 1 Resin Tank Pro');
    expect(payload.systemBlocks[0].text).toContain(MARKER);
  });

  // Every Task C instruction branch: European English, the US variants, the EXPERT3D ES/PT
  // branches, and the generic branch reached by pl / de / ru / uk / en.
  const TASK_C_BRANCHES: [string, string, string][] = [
    ['European English', 'EXPERT3D', 'ES'],
    ['Ukrainian', 'Expert-3DPrinter', 'US'],
    ['American English', 'Expert-3DPrinter', 'US'],
    ['American Spanish', 'Expert-3DPrinter', 'US'],
    ['ES', 'EXPERT3D', 'ES'],
    ['PT', 'EXPERT3D', 'ES'],
    ['PL', 'Center 3D Print', 'EU'],
    ['DE', 'Center 3D Print', 'EU'],
    ['Russian', 'Center 3D Print', 'EU'],
    ['Ukrainian', '3DDevice', 'UA'],
  ];

  it.each(TASK_C_BRANCHES)('Task C (%s, %s) carries it in its cached system text', (lang, store, group) => {
    const text = buildPromptC('<p>x</p>', lang, store, group).systemBlocks.map(b => b.text).join('\n');
    expect(text).toContain(MARKER);
  });

  it('the static clause adds no per-product text to any cached block (NFR-1)', () => {
    const a = buildPromptC('<p>x</p>', 'PL', 'Center 3D Print', 'EU', undefined, { localizedName: 'Formlabs Form Studio 1 Resin Tank Pro' });
    const b = buildPromptC('<p>x</p>', 'PL', 'Center 3D Print', 'EU', undefined, { localizedName: 'Hardened Steel Nozzle 0.4 mm' });
    expect(a.systemBlocks).toEqual(b.systemBlocks);
  });
});
